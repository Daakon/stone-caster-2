#!/usr/bin/env node
/**
 * Regenerates supabase/seed/10_base_*.sql from the hosted stone-caster-2 project.
 *
 * READ-ONLY: only issues HTTP GET requests to PostgREST. Never writes to hosted.
 * Credentials: HOSTED_SUPABASE_URL / HOSTED_SUPABASE_SERVICE_KEY, falling back to SUPABASE_URL /
 * SUPABASE_SERVICE_KEY in backend/.env (the existing hosted dev credentials).
 *
 * Scope: BASE / CONTENT data only (prompts, official worlds, rulesets, public entities, lore, tags,
 * mechanics + config registries, premade characters, ...). Never user gameplay/history, users, stories,
 * characters, turns, telemetry, payments or media. Ownership columns are remapped to the deterministic
 * local admin user so no production user ids leak into the repo.
 *
 * Usage: npm run local:seed:export
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import dotenv from 'dotenv';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const outDir = path.join(root, 'supabase', 'seed');
const LOCAL_ADMIN_ID = '00000000-0000-4000-8000-00000000a001';
const OWNER_COLS = ['owner_user_id', 'owner_id', 'created_by', 'updated_by', 'approved_by'];

const backendEnv = dotenv.parse(fs.readFileSync(path.join(root, 'backend', '.env')));
const url = (process.env.HOSTED_SUPABASE_URL || backendEnv.SUPABASE_URL || '').replace(/\/$/, '');
const key = process.env.HOSTED_SUPABASE_SERVICE_KEY || backendEnv.SUPABASE_SERVICE_KEY;
if (!url || !key) throw new Error('Missing hosted URL/service key');
if (/localhost|127\.0\.0\.1/.test(url)) throw new Error(`Refusing: ${url} is not a hosted project`);
try {
  const role = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString()).role;
  if (role !== 'service_role') throw new Error(`key role is "${role}", need service_role to read RLS-protected content`);
} catch (e) {
  if (String(e.message).startsWith('key role')) throw e; // opaque (sb_secret_) keys can't be decoded; let the API decide
}

async function get(table, query = 'select=*') {
  const res = await fetch(`${url}/rest/v1/${table}?${query}`, { method: 'GET', headers: { apikey: key, Authorization: `Bearer ${key}` } });
  if (!res.ok) throw new Error(`GET ${table} failed: ${res.status} ${await res.text()}`);
  return res.json();
}

const remap = (rows) => rows.map((r) => {
  const o = { ...r };
  for (const c of OWNER_COLS) if (o[c] != null) o[c] = LOCAL_ADMIN_ID;
  return o;
});
const byKey = (k) => (a, b) => String(a[k]).localeCompare(String(b[k]));

const written = [];
let seq = 0;
function emit(table, rows, { comment, pre = '', post = '', onConflict = true } = {}) {
  seq += 1;
  const name = `10_base_${String(seq).padStart(2, '0')}_${table}.sql`;
  const json = rows.length ? `[\n${rows.map((r) => JSON.stringify(r)).join(',\n')}\n]` : '[]';
  const sql =
    `-- GENERATED by supabase/scripts/export-hosted-base.mjs from hosted stone-caster-2 (obfadjnywufemhhhcxiy). Do not hand-edit.\n` +
    `-- ${table}: ${rows.length} row(s)${comment ? ' — ' + comment : ''}\n` +
    `set search_path to public, extensions;\n${pre}` +
    (rows.length ? `insert into public.${table}\nselect * from jsonb_populate_recordset(null::public.${table}, $seed$${json}$seed$::jsonb)${onConflict ? '\non conflict do nothing' : ''};\n` : '-- (no rows)\n') +
    post;
  fs.writeFileSync(path.join(outDir, name), sql);
  written.push(`${name} (${rows.length})`);
}

fs.mkdirSync(outDir, { recursive: true });
for (const f of fs.readdirSync(outDir)) if (f.startsWith('10_base_')) fs.unlinkSync(path.join(outDir, f));

// --- content graph (dependency order) ---
const worlds = remap((await get('chimera_worlds', 'select=*&or=(is_official.eq.true,visibility.eq.public)')).sort(byKey('key')));
const worldIds = new Set(worlds.map((w) => w.id));
emit('chimera_worlds', worlds, { comment: 'official/public worlds only' });

const rulesets = (await get('chimera_ruleset_templates')).sort(byKey('key'));
emit('chimera_ruleset_templates', rulesets);
emit('chimera_exclusion_groups', (await get('chimera_exclusion_groups')).sort(byKey('group_name')));
const tags = (await get('chimera_tags')).sort(byKey('tag_name'));
emit('chimera_tags', tags);

const entities = remap((await get('chimera_entities', 'select=*&or=(visibility.eq.public,is_official.eq.true)'))
  .filter((e) => !e.world_id || worldIds.has(e.world_id)).sort(byKey('slug')));
const entityIds = new Set(entities.map((e) => e.id));
emit('chimera_entities', entities, { comment: 'public/official entities of exported worlds' });

const lore = remap((await get('chimera_lore')).filter((l) => l.world_id && worldIds.has(l.world_id))
  .map((l) => ({ ...l, embedding: null, story_id: null, entity_id: entityIds.has(l.entity_id) ? l.entity_id : null }))
  .sort(byKey('id')));
emit('chimera_lore', lore, { comment: 'embeddings intentionally omitted (null); story links dropped' });

const knownAssetIds = new Set([...worldIds, ...entityIds, ...rulesets.map((r) => r.id), ...lore.map((l) => l.id)]);
const assetTags = (await get('chimera_asset_tags')).filter((a) => knownAssetIds.has(a.asset_id))
  .sort((a, b) => `${a.tag_id}${a.asset_id}`.localeCompare(`${b.tag_id}${b.asset_id}`));
emit('chimera_asset_tags', assetTags, { comment: 'only rows whose asset is in this seed' });
emit('chimera_world_ruleset_link', (await get('chimera_world_ruleset_link')).filter((l) => worldIds.has(l.world_id)));

// --- prompts: triggers would renumber versions / flip active flags, so disable them for the load ---
emit('prompts', remap((await get('prompts')).sort((a, b) => `${a.scope}${a.slug}${a.version}`.localeCompare(`${b.scope}${b.slug}${b.version}`))),
  { onConflict: false, pre: 'alter table public.prompts disable trigger user;\n', post: 'alter table public.prompts enable trigger user;\n' });

// --- mechanics / config registries ---
for (const [t, k] of [['mechanics_skills', 'id'], ['mechanics_conditions', 'id'], ['mechanics_resources', 'id'], ['app_config', 'key'], ['pricing_config', 'key'],
  ['ai_config', 'key'], ['feature_flags', 'key'], ['slots', 'name'], ['premade_characters', 'archetype_key'], ['localization_glossary', 'locale'],
  ['localization_rules', 'locale'], ['injection_map', 'id'], ['dialogue_config', 'id'], ['dialogue_graphs', 'id'], ['quest_graphs', 'adventure_ref']]) {
  emit(t, remap((await get(t)).sort(byKey(k))));
}
const meta = await get('config_meta');
emit('config_meta', meta);

fs.writeFileSync(path.join(outDir, '10_base_MANIFEST.txt'), `Generated by export-hosted-base.mjs\n${written.join('\n')}\n`);
console.log(`Wrote ${written.length} base seed files to ${path.relative(root, outDir)}:\n  ${written.join('\n  ')}`);
